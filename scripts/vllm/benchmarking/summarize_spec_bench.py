"""Summarize Speculative Decoding Benchmark (Spec-Bench) Results.

Aggregates JSON results generated by `vllm bench serve` under $RESULTS_DIR/bs<BS>/k<K>_rep<N>.json
or $RESULTS_DIR/k<K>_bs<BS>.json, computes E2E latency means across repetitions, calculates
speedup relative to the K=0 baseline per batch size, extracts acceptance rate %, and outputs
both a formatted console/Markdown table and a structured JSON summary.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

K_FILE_RE = re.compile(r"^k(\d+)(?:_rep(\d+))?\.json$")
K_BS_FILE_RE = re.compile(r"^k(\d+)_bs(\d+)(?:_rep(\d+))?\.json$")
BS_DIR_RE = re.compile(r"^bs(\d+)$")


def parse_result_file(file_path: Path) -> tuple[int, int, int, dict[str, Any]] | None:
    """Parse batch_size, k, rep, and data from a benchmark result file."""
    filename = file_path.name
    parent_dir = file_path.parent.name

    bs: int | None = None
    k: int | None = None
    rep: int = 1

    # Format 1: bs<BS>/k<K>_rep<REP>.json
    m_dir = BS_DIR_RE.match(parent_dir)
    if m_dir:
        bs = int(m_dir.group(1))
        m_file = K_FILE_RE.match(filename)
        if m_file:
            k = int(m_file.group(1))
            rep = int(m_file.group(2)) if m_file.group(2) else 1

    # Format 2: k<K>_bs<BS>_rep<REP>.json
    if bs is None or k is None:
        m_kbs = K_BS_FILE_RE.match(filename)
        if m_kbs:
            k = int(m_kbs.group(1))
            bs = int(m_kbs.group(2))
            rep = int(m_kbs.group(3)) if m_kbs.group(3) else 1

    if bs is None or k is None:
        return None

    try:
        with open(file_path, encoding="utf-8") as f:
            data = json.load(f)
        return bs, k, rep, data
    except Exception as e:
        print(f"WARNING: Failed to read {file_path}: {e}", file=sys.stderr)
        return None


def aggregate_spec_results(results_dir: Path) -> dict[int, dict[int, dict[str, Any]]]:
    """Aggregate benchmark results grouped by batch size and k."""
    # raw_data[bs][k] = list of rep dicts
    raw_data: dict[int, dict[int, list[dict[str, Any]]]] = defaultdict(
        lambda: defaultdict(list)
    )

    for json_file in results_dir.glob("**/*.json"):
        if (
            json_file.name.endswith(".profile.json")
            or json_file.name.endswith(".warmup.json")
            or json_file.name == "spec_benchmark_summary.json"
        ):
            continue
        parsed = parse_result_file(json_file)
        if parsed is None:
            continue
        bs, k, _, data = parsed
        raw_data[bs][k].append(data)

    summary: dict[int, dict[int, dict[str, Any]]] = {}

    for bs in sorted(raw_data.keys()):
        summary[bs] = {}
        k_entries = raw_data[bs]

        # Calculate means per k
        for k in sorted(k_entries.keys()):
            reps = k_entries[k]
            durations = []
            acceptance_rates = []
            completed_counts = []
            output_throughputs = []

            for r in reps:
                dur = (
                    r.get("duration")
                    or r.get("benchmark_duration")
                    or r.get("total_latency")
                )
                if dur is not None:
                    durations.append(float(dur))

                ar = r.get("spec_decode_acceptance_rate")
                if (
                    ar is None
                    and "spec_decode_stats" in r
                    and isinstance(r["spec_decode_stats"], dict)
                ):
                    ar = r["spec_decode_stats"].get("acceptance_rate")
                if ar is not None:
                    ar_val = float(ar)
                    # Normalize if vLLM emitted it as a percentage (e.g. 52.3) rather than ratio (0.523)
                    if ar_val > 1.0:
                        ar_val = ar_val / 100.0
                    acceptance_rates.append(ar_val)

                comp = r.get("completed")
                if comp is not None:
                    completed_counts.append(int(comp))

                ot = r.get("output_throughput") or r.get("output_token_throughput")
                if ot is not None:
                    output_throughputs.append(float(ot))

            mean_dur = sum(durations) / len(durations) if durations else 0.0
            mean_ar = (
                sum(acceptance_rates) / len(acceptance_rates)
                if acceptance_rates
                else None
            )
            mean_comp = (
                sum(completed_counts) / len(completed_counts) if completed_counts else 0
            )
            mean_ot = (
                sum(output_throughputs) / len(output_throughputs)
                if output_throughputs
                else 0.0
            )

            summary[bs][k] = {
                "num_speculations": k,
                "e2e_s": round(mean_dur, 2),
                "speedup": 1.0,
                "acceptance_rate": round(mean_ar, 4) if mean_ar is not None else None,
                "completed": mean_comp,
                "output_throughput": round(mean_ot, 2),
                "reps": len(reps),
            }

        # Compute speedup relative to k=0
        base_dur = summary[bs].get(0, {}).get("e2e_s")
        for k in summary[bs]:
            if base_dur and base_dur > 0 and summary[bs][k]["e2e_s"] > 0:
                summary[bs][k]["speedup"] = round(base_dur / summary[bs][k]["e2e_s"], 2)
            else:
                summary[bs][k]["speedup"] = 1.0

    return summary


def format_summary_table(summary: dict[int, dict[int, dict[str, Any]]]) -> str:
    """Format the aggregated results into a clear terminal and markdown table."""
    lines = []
    for bs, k_dict in sorted(summary.items()):
        lines.append(f"TPU — max_num_seqs = {bs}")
        lines.append(
            f"{'num speculations':<18} {'e2e (s)':<10} {'speedup':<10} {'acceptance metrics (%)'}"
        )
        for k, entry in sorted(k_dict.items()):
            k_str = str(k)
            e2e_str = f"{entry['e2e_s']:.2f}"
            speedup_str = f"{entry['speedup']:.2f}"
            if entry["acceptance_rate"] is not None:
                ar_str = f"{entry['acceptance_rate'] * 100:.2f}%"
            else:
                ar_str = "-"
            lines.append(f"{k_str:<18} {e2e_str:<10} {speedup_str:<10} {ar_str}")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="Summarize speculative decoding benchmark results"
    )
    parser.add_argument(
        "--results-dir",
        type=Path,
        required=True,
        help="Directory containing benchmark JSON files",
    )
    parser.add_argument(
        "--output-json", type=Path, default=None, help="Path to write summary JSON"
    )
    parser.add_argument(
        "--output-md", type=Path, default=None, help="Path to write Markdown summary"
    )
    args = parser.parse_args()

    results_dir = args.results_dir
    if not results_dir.is_dir():
        print(f"ERROR: {results_dir} is not a directory", file=sys.stderr)
        sys.exit(1)

    summary = aggregate_spec_results(results_dir)
    table_text = format_summary_table(summary)
    print(table_text)

    output_json = args.output_json or (results_dir / "spec_benchmark_summary.json")
    with open(output_json, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
    print(f"Summary JSON written to: {output_json}")

    output_md = args.output_md or (results_dir / "spec_benchmark_summary.md")
    with open(output_md, "w", encoding="utf-8") as f:
        f.write("# Speculative Decoding Benchmark Summary\n\n```\n")
        f.write(table_text)
        f.write("\n```\n")
    print(f"Markdown summary written to: {output_md}")


if __name__ == "__main__":
    main()
