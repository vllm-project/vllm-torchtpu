#!/usr/bin/env bash
# Qwen3.5 CI 的公共模型配置；入口脚本分别设置 PCP4/DP2 和 PCP8/DP4。
# 显式 role 配置优先于公共覆盖值，再使用 R11 默认值。
export MODEL_PATH="${MODEL_PATH:-${QWEN35_A3B_FP8_MODEL_PATH:-Qwen/Qwen3.5-35B-A3B-FP8}}"
export PREFILL_TP="${PREFILL_TP:-1}"
export DECODE_TP="${DECODE_TP:-2}"
export PREFILL_TPU_RAIDEN_DST_SHARDS="${PREFILL_TPU_RAIDEN_DST_SHARDS:-${TPU_RAIDEN_DST_SHARDS:-${DECODE_TP}}}"
export PREFILL_CP_KV_CACHE_INTERLEAVE_SIZE="${PREFILL_CP_KV_CACHE_INTERLEAVE_SIZE:-256}"
export PREFILL_BLOCK_SIZE="${PREFILL_BLOCK_SIZE:-768}"
export DECODE_BLOCK_SIZE="${DECODE_BLOCK_SIZE:-2304}"
export MAX_MODEL_LEN="${MAX_MODEL_LEN:-262144}"
# 完整 MTP 冷启动包含 rejection/logprobs 多 shape 编译，本机实测超过 30 分钟。
export STARTUP_TIMEOUT_S="${STARTUP_TIMEOUT_S:-3600}"
export PREFILL_MAX_NUM_BATCHED_TOKENS="${PREFILL_MAX_NUM_BATCHED_TOKENS:-${MAX_NUM_BATCHED_TOKENS:-32768}}"
export DECODE_MAX_NUM_BATCHED_TOKENS="${DECODE_MAX_NUM_BATCHED_TOKENS:-${MAX_NUM_BATCHED_TOKENS:-768}}"
export PREFILL_MAX_NUM_SEQS="${PREFILL_MAX_NUM_SEQS:-${MAX_NUM_SEQS:-128}}"
export DECODE_MAX_NUM_SEQS="${DECODE_MAX_NUM_SEQS:-${MAX_NUM_SEQS:-192}}"
export PREFILL_GPU_MEMORY_UTILIZATION="${PREFILL_GPU_MEMORY_UTILIZATION:-${GPU_MEMORY_UTILIZATION:-0.75}}"
export DECODE_GPU_MEMORY_UTILIZATION="${DECODE_GPU_MEMORY_UTILIZATION:-${GPU_MEMORY_UTILIZATION:-0.9}}"
# 32768-token batch 在 PCP4 上每 rank 为 8192，PCP8 上为 4096。
# 编译 bucket 是每 rank 的容量；PCP4 需补足最后一个 bucket。
default_prefill_compile_sizes="512,1024,2048,4096"
# PREFILL_PCP 由 source 本文件的 CI 入口设置。
# shellcheck disable=SC2153
if [[ "${PREFILL_PCP}" == "4" ]]; then
  default_prefill_compile_sizes+=",8192"
fi
export PREFILL_COMPILE_SIZES="${PREFILL_COMPILE_SIZES:-${default_prefill_compile_sizes}}"
export DECODE_COMPILE_SIZES="${DECODE_COMPILE_SIZES:-32,64,128,256,384,512,768}"
# 空值表示禁用 MTP / 使用 HBM profiling，不能用 :- 覆盖。
default_prefill_speculative_config='{"method":"mtp","num_speculative_tokens":1}'
default_decode_speculative_config='{"method":"mtp","num_speculative_tokens":3}'
export PREFILL_SPECULATIVE_CONFIG="${PREFILL_SPECULATIVE_CONFIG-${default_prefill_speculative_config}}"
export DECODE_SPECULATIVE_CONFIG="${DECODE_SPECULATIVE_CONFIG-${default_decode_speculative_config}}"
export NUM_GPU_BLOCKS_OVERRIDE="${NUM_GPU_BLOCKS_OVERRIDE-}"
export VLLM_KV_CACHE_LAYOUT="${VLLM_KV_CACHE_LAYOUT:-HND}"
export KV_CACHE_DTYPE="${KV_CACHE_DTYPE:-fp8}"
export MAMBA_SSM_CACHE_DTYPE="${MAMBA_SSM_CACHE_DTYPE:-bfloat16}"
export ATTENTION_BACKEND="${ATTENTION_BACKEND:-CUSTOM}"
export ASYNC_SCHEDULING="${ASYNC_SCHEDULING:-1}"
export ENABLE_PREFIX_CACHING="${ENABLE_PREFIX_CACHING:-1}"
export MAMBA_CACHE_MODE="${MAMBA_CACHE_MODE:-align}"
export TPU_VLLM_ENABLE_UNIFIED_BLOCK_POOL="${TPU_VLLM_ENABLE_UNIFIED_BLOCK_POOL:-1}"
export VLLM_PREFIX_CACHE_RETENTION_INTERVAL="${VLLM_PREFIX_CACHE_RETENTION_INTERVAL:-0}"
export TPU_RAIDEN_PREFIX_AWARE_LOAD="${TPU_RAIDEN_PREFIX_AWARE_LOAD:-1}"
export TPU_RAIDEN_TRANSFER_PARALLELISM="${TPU_RAIDEN_TRANSFER_PARALLELISM:-${PREFILL_PCP}}"
export TPU_PARALLEL_PRECOMPILE="${TPU_PARALLEL_PRECOMPILE:-1}"
export USE_MOE_FUSED_EP_KERNEL="${USE_MOE_FUSED_EP_KERNEL:-1}"
export MOE_FUSED_EP_V2_SHARDED_PLAN="${MOE_FUSED_EP_V2_SHARDED_PLAN:-1}"
export MOE_REQUANTIZE_BLOCK_SIZE="${MOE_REQUANTIZE_BLOCK_SIZE:-128}"
export ONEHOT_MOE_PERMUTE_THRESHOLD="${ONEHOT_MOE_PERMUTE_THRESHOLD:-32768}"
export RAGGED_GATHER_REDUCE_VERSION="${RAGGED_GATHER_REDUCE_VERSION:-v3}"
