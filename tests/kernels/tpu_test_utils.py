"""Shared TPU backend assertion helper for kernel unit and parity tests."""

from __future__ import annotations

import jax
import pytest


def require_tpu() -> None:
    """Fail the test if the active JAX backend is not TPU."""
    try:
        backend = jax.default_backend()
    except Exception as exc:
        pytest.fail(f"JAX TPU backend failed to initialize: {exc}")
    if backend != "tpu":
        pytest.fail(f"Expected JAX TPU backend, got {backend}.")
