def selftest() -> int:
    L = 3
    relay = "  %copy.3 = bf16[10240,320]{0,1} copy(%p5)"
    cases = []
    for arm in ARMS:
        k = ARM_KERNEL[arm]
        cases.append((f"{arm} engaged", arm, [_cc(k)] * L, True))
        cases.append((f"{arm} with one call missing", arm, [_cc(k)] * (L - 1), False))
        cases.append((f"{arm} with an up relayout copy", arm, [_cc(k)] * L + [relay], False))
        other = W1FSN if k == W1FN else W1FN
        cases.append((f"{arm} with a stray {other} call", arm, [_cc(k)] * L + [_cc(other)], False))
    cases += [
        ("B with an unnamed custom call fed by the kernel still engaged (operands never count)", "B",
         [_cc(W1FN)] * L + ["  %custom-call.9 = (bf16[288,2560]{1,0}) custom-call(%" + W1FN + ".7), custom_call_target=\"x\""], True),
        ("B with _w1fs-named calls is not engaged (prefix rule)", "B", [_cc(W1FSN)] * L, False),
        ("X with _w1fsm-named calls is not engaged (prefix rule)", "X", [_cc(XMN)] * L, False),
        ("X with _w1f-named calls is not engaged", "X", [_cc(W1FN)] * L, False),
    ]
    bad = 0
    for label, arm, lines, want in cases:
        got = engaged(arm, kernel_counts("\n".join(lines)), L)
        print(f"Q38_HCKMB_SELFTEST {'ok ' if got == want else 'BAD'} {label}: got {got} want {want}")
        bad += got != want
    for label, arm, rows, cen, want in _census_cases():
        got = census_ok(arm, rows, cen)[0]
        print(f"Q38_HCKMB_SELFTEST {'ok ' if got == want else 'BAD'} census {label}: got {got} want {want}")
        bad += got != want
    cfg_ok = ROWS == (288, 320) and HEALTH_ROWS == (160, 288, 320, 384, 496) and ARMS == ("B", "X", "XD", "XO") \
        and ABBA == ("B", "X", "X", "B") and NEG_ARM == "XM" and ITERS == 150 and (L_LONG, L_SHORT) == (24, 4) \
        and GEO == dict(HC=4, H=2560, LR=320, EPS=1e-6) and WANT_LIBTPU == SERVED_LIBTPU + " " + DVFS + "=7 " + LB_OFF
    print(f"Q38_HCKMB_SELFTEST {'ok ' if cfg_ok else 'BAD'} plan rows {ROWS} health {HEALTH_ROWS} arms {ARMS} order {ABBA} "
          f"neg {NEG_ARM} iters {ITERS} chain {L_LONG}/{L_SHORT} libtpu {WANT_LIBTPU}")
    bad += not cfg_ok
    kp = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "vllm_torchtpu", "kernels", "qwen4_exp",
                      "hc_decode_wide.py")
    try:
        text = open(kp).read()
        anchors = all(text.count(old) == 1 and text.count(new) == 0 for old, new in XM_EDITS)
    except OSError:
        anchors = False
    print(f"Q38_HCKMB_SELFTEST {'ok ' if anchors else 'BAD'} XM edit anchors once (replacements absent) in the tree's hc_decode_wide.py")
    bad += not anchors
    print("Q38_HCKMB_SELFTEST", "PASS" if not bad else f"FAIL ({bad})")
    return 0 if not bad else 1


def mutants() -> int:
    """Each mutant weakens one rule; the selftest must fail under every one."""
    g = globals()
    orig = {k: g[k] for k in ("ARM_KERNEL", "call_kernel", "RELAYOUT_RE", "_KERNELS", "XM_EDITS", "census_ok", "nb2")}
    muts = {
        "X rule names the served kernel": ("ARM_KERNEL", {**orig["ARM_KERNEL"], "X": W1FN}),
        "kernel name read from any operand": ("call_kernel", lambda ln: next((k for k in orig["_KERNELS"] if k in ln), None)),
        "plain prefix match, shortest name first": ("call_kernel", lambda ln: next(
            (k for k in sorted(orig["_KERNELS"], key=len) if ln.split(" = ", 1)[0].strip().lstrip("%").startswith(k)), None)),
        "relayout check blind": ("RELAYOUT_RE", re.compile(r"$^")),
        "XM edit anchor stale": ("XM_EDITS", (("        tag += \"s\"  # stale\n", XM_EDITS[0][1]), XM_EDITS[1])),
        "census: X accepted whatever it shows": ("census_ok", lambda arm, rows, cen: (True, "ok") if arm == "X" else orig["census_ok"](arm, rows, cen)),
        "census: one-pass blocks = default blocks": ("nb2", nblocks),
    }
    bad = 0
    import contextlib
    import io
    for name, (sym, val) in muts.items():
        g[sym] = val
        try:
            with contextlib.redirect_stdout(io.StringIO()):
                rc = selftest()
        finally:
            for k, v in orig.items():
                g[k] = v
        caught = rc != 0
        print(f"Q38_HCKMB_MUTANT {'killed  ' if caught else 'SURVIVED'} {name}")
        bad += not caught
    print("Q38_HCKMB_MUTANTS", "PASS" if not bad else f"FAIL ({bad} survived)", f"({len(muts)} mutants)")
    return 0 if not bad else 1


