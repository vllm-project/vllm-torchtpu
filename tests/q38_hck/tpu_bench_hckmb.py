def _mask(txt):
    txt = re.sub(r"\S+\.py(?:\.txt)?:\d+(?::\d+)?", "<src>", txt)
    txt = re.sub(r"q38_hc_decode_wide_xm", "<mod>", txt)
    return re.sub(r"0x[0-9a-f]+", "<addr>", txt)


def census(arm, rows, geo=GEO) -> dict:
    """dot_general / dma_start / dma_wait counts and a masked text hash of one call's jaxpr (the kernel jaxpr is printed inside it)."""
    import jax
    import jax.numpy as jnp
    s = jax.ShapeDtypeStruct
    HC, H, LR = geo["HC"], geo["H"], geo["LR"]
    W = HC * H
    bf = jnp.bfloat16
    p = dict(w=s((W,), bf), down=s((LR, W), bf), up=s((W, LR), bf), inject=s((HC, W), bf))

    def f(prev, block, pinj, pp):
        return one_call(arm, prev, block, pinj, pp, geo)

    txt = _mask(str(jax.make_jaxpr(f)(s((rows, W), bf), s((rows, H), bf), s((rows, HC), jnp.float32), p)))
    return {"dots": len(re.findall(r"\bdot_general\b", txt)), "dma_start": len(re.findall(r"\bdma_start\b", txt)),
            "dma_wait": len(re.findall(r"\bdma_wait\b", txt)), "hash": hashlib.sha256(txt.encode()).hexdigest()[:16]}


def census_all(rows_l, arms=ARMS) -> dict:
    out = {}
    for rows in rows_l:
        cen = {}
        for arm in arms:
            try:
                cen[arm] = census(arm, rows)
            except Exception as e:  # noqa: BLE001
                cen[arm] = {"error": f"{type(e).__name__}: {str(e)[:600]}"}
        out[str(rows)] = {"census": cen, "ok": {a: census_ok(a, rows, cen)[0] for a in arms},
                          "why": {a: census_ok(a, rows, cen)[1] for a in arms}}
    return out


# ---------------------------------------------------------------- health
def health(mesh, geo, rows, ws, x, interpret=False) -> dict:
    """One call per arm and the negative control on real inputs. Gate: B finite and equal on all 8 cores. Recorded: X / XD / XO / XM
    bitwise against B (mixed, injection gate, h), their finiteness and core equality."""
    import jax
    prev, block, pinj = x
    out, err = {}, {}
    for arm in list(ARMS) + [NEG_ARM]:
        try:
            f = build_single(arm, geo, mesh, interpret)
            o = jax.device_get(f(prev, block, pinj, ws[0]))
            out[arm] = [np.asarray(np.asarray(v).astype(np.float32)) for v in o]
        except Exception as e:  # noqa: BLE001
            err[arm] = f"{type(e).__name__}: {str(e)[:600]}"
    bits = lambda v: np.ascontiguousarray(np.float32(v)).view(np.uint32)  # noqa: E731
    rep = {"ran": {a: a in out for a in list(ARMS) + [NEG_ARM]}, "errors": err,
           "finite": {k: bool(all(np.isfinite(v).all() for v in o)) for k, o in out.items()},
           "cores_equal": {k: bool(all(np.array_equal(bits(v[0]), bits(v[i])) for v in o for i in range(N))) for k, o in out.items()},
           "bitwise_vs_B": {}, "ndiff_vs_B": {}}
    B = out.get("B")
    for arm in ("X", "XD", "XO", NEG_ARM):
        A = out.get(arm)
        if B is None or A is None:
            continue
        rep["bitwise_vs_B"][arm] = [bool(np.array_equal(bits(a[0]), bits(b[0]))) for a, b in zip(A, B)]
        rep["ndiff_vs_B"][arm] = [int((bits(a[0]) != bits(b[0])).sum()) for a, b in zip(A, B)]
    rep["ok"] = bool(B is not None and rep["finite"].get("B") and rep["cores_equal"].get("B"))
    return rep


def per_call(long_s, short_s, cl, cs) -> dict:
    ml, ms = statistics.median(long_s), statistics.median(short_s)
    n = len(long_s) // 2
    halves = [None, None]
    if n >= 2:
        f = lambda a, b: round((statistics.median(a) - statistics.median(b)) / (cl - cs), 3)  # noqa: E731
        halves = [f(long_s[:n], short_s[:n]), f(long_s[n:], short_s[n:])]
    return {"us_per_call": round((ml - ms) / (cl - cs), 3), "halves": halves, "long_median_us": round(ml, 2),
            "short_median_us": round(ms, 2), "samples_long_us": [round(v, 2) for v in long_s],
            "samples_short_us": [round(v, 2) for v in short_s]}


