def nblocks(rows):
    """hc_decode_wide.row_blocks(rows) count at the default 128-row block (C)."""
    return -(-rows // 128)


def nb2(rows):
    """Phase B2 blocks under sched_onepass (C: row blocks of at most ONEPASS_ROWS = 320 rows)."""
    return -(-rows // 320)


def census_ok(arm, rows, cen) -> tuple:
    """(ok, why) for one arm at one row; cen = {arm: {dots, dma_start, dma_wait, hash}} for that row."""
    c, b = cen.get(arm), cen.get("B") or {}
    if not c or "dots" not in c:
        return False, "no census"
    if c.get("dma_start", 0) <= 0 or c.get("dma_start") != c.get("dma_wait"):
        return False, f"dma_start {c.get('dma_start')} / dma_wait {c.get('dma_wait')} (want equal, > 0)"
    br = GEO["HC"]
    want_dots = {"B": 1 + br * nblocks(rows), "XD": 1 + br * nblocks(rows), "X": 1 + br * nb2(rows), "XO": 1 + br * nb2(rows)}[arm]
    if c["dots"] != want_dots:
        return False, f"dots {c['dots']} != {want_dots}"
    if arm == "B":
        return True, "ok"
    if "dma_start" not in b:
        return False, "no B census"
    slabs = 6  # (DN_SLABS - 1) + (branches - 1)
    fewer_out = nblocks(rows) - nb2(rows)
    want_dma = {"XD": b["dma_start"] + slabs, "XO": b["dma_start"] - fewer_out, "X": b["dma_start"] + slabs - fewer_out}[arm]
    if c["dma_start"] != want_dma:
        return False, f"dma_start {c['dma_start']} != {want_dma}"
    if c.get("hash") == b.get("hash"):
        return False, "jaxpr text equals B's"
    return True, "ok"


# ---------------------------------------------------------------- libtpu (ARB1 / K3DX / HCBIND rule; B1 clock pinned)
def check_barrier(final: str) -> None:
    toks = [t for t in final.split() if t.split("=")[0] == LB]
    if toks != [LB_OFF]:
        raise SystemExit(f"Q38_BARRIER_ASSERT FAIL: launch-barrier tokens {toks} (want exactly ['{LB_OFF}'])")


def check_clock(final: str) -> None:
    """Exactly one --xla_tpu_dvfs_p_state token, and it is =7 (token-exact; no regex)."""
    toks = [t for t in final.split() if t.split("=")[0] == DVFS]
    if toks != [DVFS + "=7"]:
        raise SystemExit(f"Q38_CLOCK_ASSERT FAIL: dvfs tokens {toks} (want exactly ['{DVFS}=7'])")


def apply_cfg() -> str:
    """LIBTPU_INIT_ARGS pinned to the B1 decode set (2 served flags + p7) + the barrier off, whatever the pod inherited."""
    final = WANT_LIBTPU
    check_barrier(final)
    check_clock(final)
    os.environ["LIBTPU_INIT_ARGS"] = final
    return final


def barrier_selftest() -> int:
    bad = 0
    saved = os.environ.get("LIBTPU_INIT_ARGS")
    for base in ("--a=1 " + LB + "=true --b=2", LB + "=true " + LB + "=true", "--a=1", LB_OFF, "", LB, RT + "=true",
                 DVFS + "=3", DVFS + "=7 " + DVFS + "=7"):
        os.environ["LIBTPU_INIT_ARGS"] = base
        try:
            final = apply_cfg()
            ok = [t for t in final.split() if t.split("=")[0] == LB] == [LB_OFF]
            ok &= not any(t.split("=")[0] == RT for t in final.split())
            ok &= final == WANT_LIBTPU and [t for t in final.split() if t.split("=")[0] == DVFS] == [DVFS + "=7"]
        except SystemExit:
            ok = False
        bad += not ok
    for final, want in ((LB + "=true", False), (LB_OFF + " " + LB_OFF, False), ("--a=1", False),
                        (LB_OFF + " " + LB + "=true", False), (LB, False), ("--a=1 " + LB_OFF, True)):
        try:
            check_barrier(final)
            got = True
        except SystemExit:
            got = False
        print(f"Q38_BARRIER_SELFTEST check_barrier({final!r}) -> {'accept' if got else 'refuse'} "
              f"(want {'accept' if want else 'refuse'})")
        bad += got != want
    for final, want in ((DVFS + "=7", True), (DVFS + "=3", False), ("", False), (DVFS + "=7 " + DVFS + "=7", False),
                        (DVFS + "=7+VLLM_CACHE_ROOT=/x", False), (DVFS, False), ("--a=1 " + DVFS + "=7 --b", True)):
        try:
            check_clock(final)
            got = True
        except SystemExit:
            got = False
        print(f"Q38_BARRIER_SELFTEST check_clock({final!r}) -> {'accept' if got else 'refuse'} "
              f"(want {'accept' if want else 'refuse'})")
        bad += got != want
    if saved is None:
        os.environ.pop("LIBTPU_INIT_ARGS", None)
    else:
        os.environ["LIBTPU_INIT_ARGS"] = saved
    print("Q38_BARRIER_SELFTEST", "PASS" if not bad else f"FAIL ({bad})")
    return 0 if not bad else 1


