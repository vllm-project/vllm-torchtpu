def edited_module(tag, edits):
    """The tree's hc_decode_wide.py with counted edits (each anchor exactly once before, its replacement exactly once after), loaded
    from a temp copy as its own module (its own jit caches)."""
    if tag not in _MODS:
        import importlib.util
        import tempfile

        from vllm_torchtpu.kernels.qwen4_exp import hc_decode_wide as hw
        text = open(hw.__file__).read()
        for old, new in edits:
            assert text.count(old) == 1, f"{tag}: anchor not unique in hc_decode_wide.py: {old[:60]!r}"
            text = text.replace(old, new)
            assert text.count(new) == 1, f"{tag}: replacement not unique: {new[:60]!r}"
        fd, p = tempfile.mkstemp(suffix=f"_hc_decode_wide_{tag}.py")
        os.close(fd)
        open(p, "w").write(text)
        spec = importlib.util.spec_from_file_location(f"q38_hc_decode_wide_{tag}", p)
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        _MODS[tag] = m
    return _MODS[tag]


