class _TwinMixin:
    """`twin_split` on the L1-IDX DCP-4 group block (module docstring); inert at more than R / 2 request slots."""

    def __init__(self, *, twin_split: int = 0, **kw: Any) -> None:
        super().__init__(**kw)
        self.twin_split = int(twin_split)
        if self.twin_split:
            assert self.dcp == 4 and self.shard_index and self.loop_requests and self.union_lean, (
                "q38 HXIDX twin_split: main-KV DCP 4 with the sharded indexer, the request loop and D08 S1 B2",
                self.dcp, self.shard_index, self.loop_requests, self.union_lean)
            assert self.union_qsplit == 1 and not self.compressed_dcp, (
                "q38 HXIDX twin_split: QSPLIT 1 (strided union rows), no compressed-key DCP", self.union_qsplit)

    # ------------------------------------------------------------ pairing
    def _twin_on(self, ex: ExecSpec) -> bool:
        """The pair split runs only where it helps: at most R / 2 request slots (16 rows at TP 8), even R and T."""
        return bool(self.twin_split) and ex.R == 8 and ex.T % 2 == 0 and ex.MB // ex.T <= ex.R // 2

    def _runs(self, ex: ExecSpec) -> int:
        return ex.R // 2 if self._twin_on(ex) else super()._runs(ex)

    def _run(self, ctx: Any) -> Any:
        return ctx.me // 2 if self._twin_on(ctx.ex) else super()._run(ctx)

    # ------------------------------------------------------------ scratch
    def scratch(self, g: Any, ex: ExecSpec, plan: Any) -> list[ScratchReq]:
        out = super().scratch(g, ex, plan)
        if not self._twin_on(ex):
            return out
        S = self.max_groups // 128
        return out + [
            ScratchReq("qtw_send", pltpu.VMEM((S // 2, 128), I32)),
            ScratchReq("qtw_recv", pltpu.VMEM((S // 2, 128), I32)),
            ScratchReq("qtw_tsend", pltpu.VMEM((8, 128), I32)),
            ScratchReq("qtw_trecv", pltpu.VMEM((8, 128), I32)),
            ScratchReq("qtw_ssem", pltpu.SemaphoreType.DMA((2,))),
            ScratchReq("qtw_rsem", pltpu.SemaphoreType.DMA((2,))),
        ]

    # ------------------------------------------------------------ the twin exchange (step 3)
    def _twin_exchange(self, ctx: Any, lo: Any, n: int) -> None:
        """Rows `[lo, lo + n)` (one request): send the partner the code rows of its parity and this twin's rows' state;
        receive the partner's. The received code rows stay in `qtw_recv` (OR-ed in by `_qsplit_compact`)."""
        scr, me = ctx.scr, ctx.me
        S = self.max_groups // 128
        h = n // 2
        par = jax.lax.rem(me, 2)
        lane = jax.lax.broadcasted_iota(I32, (1, 128), 1)
        with ctx.stream.sc("qsa_twx", 2):
            for p in (0, 1):  # static strides: this twin's parity p sends the rows of parity 1 - p
                @pl.when(par == p)
                def _(p=p):
                    scr["qtw_send"][...] = scr["qu_code"][pl.ds(1 - p, S // 2, stride=2), :]
            own = lo + par * h
            tile = jnp.zeros((8, 128), I32)
            row = jax.lax.broadcasted_iota(I32, (8, 128), 0)
            ln = jax.lax.broadcasted_iota(I32, (8, 128), 1)
            for j in range(h):
                r = own + j
                vals = (scr["qi_kvl"][r], scr["qc_sga"][r], jnp.sum(jnp.where(lane == 0, scr["qi_th"][r], 0)),
                        jnp.sum(jnp.where(lane == 0, scr["qi_tm"][r], 0)), jnp.sum(jnp.where(lane == 0, scr["qi_nv"][r], 0)))
                for k, v in enumerate(vals):
                    tile = jnp.where((row == j) & (ln == k), v, tile)
            scr["qtw_tsend"][...] = tile
            peer = me ^ 1
            descs = [
                pltpu.make_async_remote_copy(src_ref=scr[s], dst_ref=scr[d], send_sem=scr["qtw_ssem"].at[i],
                                             recv_sem=scr["qtw_rsem"].at[i], device_id=(peer,),
                                             device_id_type=pl.DeviceIdType.MESH)
                for i, (s, d) in enumerate((("qtw_send", "qtw_recv"), ("qtw_tsend", "qtw_trecv")))
            ]
            ctx.comm.exchange(descs)
            other = lo + (1 - par) * h
            got = scr["qtw_trecv"][...]
            for j in range(h):
                r = other + j
                gj = [jnp.sum(jnp.where((row == j) & (ln == k), got, 0)) for k in range(5)]
                scr["qi_kvl"][r] = gj[0]
                scr["qc_sga"][r] = gj[1]
                scr["qi_th"][r] = jnp.broadcast_to(gj[2], (1, 128))
                scr["qi_tm"][r] = jnp.broadcast_to(gj[3], (1, 128))
                scr["qi_nv"][r] = jnp.broadcast_to(gj[4], (1, 128))

    # ------------------------------------------------------------ union halves of this twin's parity (step 4)
    def _qsplit_compact(self, ctx: Any, q: Any, KU: int, npr: int) -> None:
        if not self._twin_on(ctx.ex):
            return super()._qsplit_compact(ctx, q, KU, npr)
        scr = ctx.scr
        D = max(self.dcp, 1)
        S = self.max_groups // 128
        gpp = ctx.extra[POOL].shape[1] // ua.MICRO
        assert gpp == 128 and S % (2 * D) == 0, ("q38 HXIDX: QSPLIT rows (128 groups per pool block)", gpp, S, D)
        par = jax.lax.rem(ctx.me, 2)
        for p in (0, 1):
            @pl.when(par == p)
            def _(p=p):
                for r in range(p, D, 2):  # half r: rows r, r + D, ...; the partner's bits of those rows sit at
                    code = (scr["qu_code"][pl.ds(r, S // D, stride=D), :]  # qtw_recv rows (r - p) / 2 + 2 j
                            | scr["qtw_recv"][pl.ds((r - p) // 2, S // D, stride=2), :])
                    self._compact_rows(ctx, q, r, code, KU, npr, D)

    # ------------------------------------------------------------ the all-rank exchange (step 5)
    def _exchange_lean(self, ctx: Any) -> None:
        """`_LeanMixin._exchange_lean` with each half sent only to the same-parity cores (`me ^ 2 / 4 / 6`), into the
        receiver's slot of this pair (`qgl_recv[run]`, the slot `q // npr` readers use); the tails carry `qu_n` of
        this twin's halves and every row's `qi_kvl` / `qc_sga` (both twins hold all rows after the twin exchange)."""
        ex = ctx.ex
        if not self._twin_on(ex):
            return super()._exchange_lean(ctx)
        scr, T = ctx.scr, ex.T
        nreq, KU = ex.MB // T, self._union_width(ex)
        npr = self._shard_rows(ex)[0]
        me, D = ctx.me, max(self.dcp, 1)
        lane = jax.lax.broadcasted_iota(I32, (1, 128), 1)
        run = self._run(ctx)
        with ctx.stream.sc("qsa_ux", 2):
            scr["qi_z"][...] = jnp.zeros((1, 128), I32)

            def pack(i: Any, carry: Any) -> Any:
                q = jnp.minimum(run * npr + i, nreq - 1)
                tail = jnp.zeros((1, 128), I32)
                for r in range(D):
                    tail = jnp.where(lane == r, scr["qu_n"][q, r], tail)
                for t in range(T):
                    tail = jnp.where(lane == D + t, scr["qi_kvl"][q * T + t], tail)
                    tail = jnp.where(lane == D + T + t, scr["qc_sga"][q * T + t], tail)
                for hh in range(D):
                    scr["qgl_send"][hh, i, :, pl.ds(2 * KU, 128)] = tail
                return carry

            jax.lax.fori_loop(0, npr, pack, 0)
            scr["qgl_recv"][run] = scr["qgl_send"][jax.lax.rem(me, D)]
            descs = [
                pltpu.make_async_remote_copy(
                    src_ref=scr["qgl_send"].at[jax.lax.rem(me ^ off, D)], dst_ref=scr["qgl_recv"].at[run],
                    send_sem=scr["qgl_ssem"].at[k], recv_sem=scr["qgl_rsem"].at[k], device_id=(me ^ off,),
                    device_id_type=pl.DeviceIdType.MESH)
                for k, off in enumerate((2, 4, 6))
            ]
            ctx.comm.exchange(descs)

            def unpack(q: Any, carry: Any) -> Any:
                o = q // npr
                tail = scr["qgl_recv"][o, q - o * npr, :, pl.ds(2 * KU, 128)]
                for r in range(D):
                    scr["qu_n"][q, r] = jnp.sum(jnp.where(lane == r, tail, 0))
                for t in range(T):
                    scr["qi_kvl"][q * T + t] = jnp.sum(jnp.where(lane == D + t, tail, 0))
                    scr["qc_sga"][q * T + t] = jnp.sum(jnp.where(lane == D + T + t, tail, 0))
                return carry

            jax.lax.fori_loop(0, nreq, unpack, 0)

    # ------------------------------------------------------------ selection
    def _select(self, ctx: Any, l: Any, slot: Any) -> None:  # noqa: E741
        if not self._twin_on(ctx.ex):
            return super()._select(ctx, l, slot)
        key = (ctx.ex.MB, ctx.ex.R, ctx.ex.T)
        TWIN_SELECT_TRACES[key] = TWIN_SELECT_TRACES.get(key, 0) + 1
        return self._twin_select(ctx, l, slot)

    # ------------------------------------------------------------ generated (gen_qsa_full_twin.py)
    def _twin_select(self, ctx: Any, l: Any, slot: Any) -> None:  # noqa: E741
        """`qsa_full_idx._IdxMixin._select` (GENERATED copy, scratch/hxdev/c/gen_qsa_full_twin.py) with the twin
        split: `select_rows` thresholds and selects this twin's half of the request's rows, then the twin exchange,
        then the union halves of this twin's parity (`_qsplit_compact`)."""
        ex, scr, g = ctx.ex, ctx.scr, ctx.g
        MB, T, K, G = ex.MB, ex.T, self.budget, self.max_groups
        S, rot = G // 128, self.rot
        ctx._slot = slot
        lean, batch, recent = self.union_lean, self._bg, self._br
        with ctx.stream.sc("qsa_idx_proj", 2), ctx.stream.segment(lazy=False):
            yi = rnd(ctx.stream.dmatmul(IDX_W, scr["xb"], IDX_N))
        cos = scr["qf_rope"][:, : rot // 2]
        sin = scr["qf_rope"][:, rot // 2 : rot]
        iq = ix.index_query(yi, ctx.sm(slot, "qsa_iqn"), cos, sin, rot, g.eps, pltpu.bitcast)
        raw = yi[:, 4 * ix.IDX_DIM : 5 * ix.IDX_DIM]
        scr["qc_ir"][...] = raw.astype(BF16)
        o = ctx.stream.sp.block_ord(l, self.name)
        outs = [
            pltpu.make_async_copy(scr[src], ctx.O[dst].at[o, pl.ds(0, MB)], scr["qc_osem"].at[i])
            for i, (src, dst) in enumerate((("qf_kr", KR_NEW), ("qc_ir", IR_NEW)))
        ]
        for c in outs:
            c.start()
        nreq = MB // T
        for q in range(nreq):
            for t in range(T):
                for h in range(ix.IDX_HEADS):
                    i = t * ix.IDX_HEADS + h
                    scr["qi_q"][q, i : i + 1, :] = iq[h][q * T + t : q * T + t + 1]
        NC = self.n_chunks
        gid = (
            jax.lax.broadcasted_iota(I32, (T, NC, S // NC, 128), 1) * (G // NC)
            + jax.lax.broadcasted_iota(I32, (T, NC, S // NC, 128), 2) * 128
            + jax.lax.broadcasted_iota(I32, (T, NC, S // NC, 128), 3)
        )
        npr = self._shard_rows(ex)[0] if self.shard_index else nreq

        def select_rows(lo: Any, n: int, s0: Any) -> None:
            """Thresholds, row selection and the request's union (rows `[lo, lo + n)`, scores at `qi_s[s0 …]`)."""
            tw = jax.lax.rem(ctx.me, 2) * (n // 2)  # q38 HXIDX: this twin's half of the request's rows
            lo_r, n_r, s0_r = lo + tw, n // 2, s0 + tw
            rid = jax.lax.broadcasted_iota(I32, (n_r, 1, 1), 0) + lo_r
            nv = jnp.zeros((n_r, 1, 1), I32)
            for i in range(n_r):  # `lo_r` is traced
                nv = jnp.where(rid == lo_r + i, ctx.extra[NVIS][lo_r + i], nv)
            ids = (
                jax.lax.broadcasted_iota(I32, (n_r, S, 128), 1) * 128
                + jax.lax.broadcasted_iota(I32, (n_r, S, 128), 2)
            )
            sc = pltpu.bitcast(scr["qi_s"][pl.ds(s0_r, n_r)].reshape(n_r, S, 128), I32)
            bits = jnp.where(ids < nv, sc, -1)
            with ctx.stream.sc("qsa_thr", 2):
                thr, tmax = self._idx_thresholds(bits, ids, nv, K, G)  # q38 L1-IDX S2P radix-2
            scr["qi_th"][pl.ds(lo_r, n_r)] = jnp.broadcast_to(thr, (n_r, 1, 128))
            scr["qi_tm"][pl.ds(lo_r, n_r)] = jnp.broadcast_to(tmax, (n_r, 1, 128))
            scr["qi_nv"][pl.ds(lo_r, n_r)] = jnp.broadcast_to(nv, (n_r, 1, 128))
            consts = ix.compact_consts(S, K)
            lid = consts[-1]
            scr["qi_z"][...] = jnp.zeros((1, 128), I32)
            scr["qu_code"][...] = jnp.zeros((S, 128), I32)

            def row(r: Any, carry: Any) -> Any:
                nvr = scr["qi_nv"][r][:, :1]
                ga = ctx.extra[CTXQ][r // T] // 4
                b = jnp.where(lid < nvr, pltpu.bitcast(scr["qi_s"][r - lo + s0].reshape(S, 128), I32), -1)
                th, tm = scr["qi_th"][r][:, :1], scr["qi_tm"][r][:, :1]
                ov = nvr > K
                sel = (ov & ((b > th) | ((b == th) & (lid <= tm)))) | (~ov & (b >= 0))
                # Recent groups (>= g_a) leave the pool path; remember whether g_a was selected.
                scr["qc_sga"][r] = jnp.sum((sel & (lid == ga)).astype(I32))
                kept = jnp.sum((sel & (lid < ga)).astype(I32))
                # Row bit r - lo of every pool-path group it selects.
                scr["qu_code"][...] = scr["qu_code"][...] | jnp.where(sel & (lid < ga), jnp.left_shift(1, r - lo), 0)
                if not lean:  # MM: the row's compacted ids (read only by the per-row path and the debug output)
                    bp = jnp.where(lid < ga, b, -1)
                    b2 = jnp.where(sel & (lid < ga), bp, -1)
                    pos = ix.compact_row(
                        b2, jnp.zeros((1, 1), I32), jnp.zeros((1, 1), I32) + G,
                        jnp.zeros((1, 1), I32) + kept, K, consts,
                    )
                    scr["qi_id"][r] = pos
                    cs = [
                        pltpu.make_async_copy(
                            scr["qi_id"].at[r], scr["qi_ids"].at[pl.ds(r, 1), pl.ds(0, K)], scr["qi_sem"].at[1]
                        ),
                        pltpu.make_async_copy(
                            scr["qi_z"], scr["qi_ids"].at[pl.ds(r, 1), pl.ds(K, 128)], scr["qi_sem"].at[2]
                        ),
                    ]
                    for c in cs:
                        c.start()
                    for c in cs:
                        c.wait()
                scr["qi_kvl"][r] = 4 * kept
                return carry

            with ctx.stream.sc("qsa_rowsel", 2):
                jax.lax.fori_loop(lo_r, lo_r + n_r, row, 0)
            self._twin_exchange(ctx, lo, n)  # q38 HXIDX: code rows + partner rows' state, on-chip
            KU, D = self._union_width(ex), max(self.dcp, 1)
            with ctx.stream.sc("qsa_ucompact", 2):
                if self.union_qsplit and D > 1:  # q38 L1-IDX QSPLIT: each DCP rank's own rows of the code array
                    self._qsplit_compact(ctx, lo // T, KU, npr)
                else:
                    # Main-KV DCP: one union per DCP rank over the groups it owns (group g lives on rank
                    # (g // groups-per-page) % D), each compacted ascending.
                    code_all = scr["qu_code"][...]
                    gpp = ctx.extra[POOL].shape[1] // ua.MICRO
                    gidx = jax.lax.broadcasted_iota(I32, (S, 128), 0) * 128 + jax.lax.broadcasted_iota(I32, (S, 128), 1)
                    for r in range(D):
                        code = code_all if D == 1 else jnp.where(jax.lax.rem(gidx // gpp, D) == r, code_all, 0)
                        self._compact(ctx, lo // T, r, code, KU, npr)

        self.load_tables(ctx, l)
        if self.loop_requests:
            for q in range(nreq):  # static stores into the request-major copies
                scr["qc_irq"][q] = raw[q * T : (q + 1) * T]
                scr["qc_kvq"][q] = scr["qf_kv"][q * T : (q + 1) * T].astype(F32)
        if recent:
            self._recent_issue(ctx, l)
        if batch:
            self._new_groups(ctx, l, raw)

        def group(q: Any, raw_q: Any) -> tuple[Any, Any]:
            """(fresh key, group id) of request `q`'s completed group."""
            if batch:
                return scr["qb_ck"][q], self._gc(ctx, q)
            return self._new_group(ctx, l, q, raw_q)

        def score_merge(q: Any, qr: Any, ck: Any, gc: Any, first: Any, last: Any) -> None:
            self._score_request(ctx, q, qr, self.tab_base(ctx, l), row0=0, first=first, last=last, c_off=0)
            s_new = ix.score_rows(qr, jnp.broadcast_to(ck.astype(BF16), (8, ix.IDX_DIM)))
            scr["qi_s"][0:T] = jnp.where(gid == gc, s_new[:, :1].reshape(T, 1, 1, 1), scr["qi_s"][0:T])
            select_rows(q * T, T, 0)

        exchange = self._exchange_lean if lean else self._exchange_selection
        if self.loop_requests:

            def req(q: Any, carry: Any) -> Any:
                ck, gc = group(q, scr["qc_irq"][q] if not batch else None)

                def own() -> None:
                    score_merge(
                        q, scr["qi_q"][q].astype(BF16), ck, gc, jax.lax.rem(q, npr) == 0,
                        (jax.lax.rem(q, npr) == npr - 1) | (q == nreq - 1),
                    )

                if self.shard_index:
                    pl.when(q // npr == self._run(ctx))(own)
                else:
                    own()
                if not recent:
                    self._recent_tile(ctx, l, q)
                return carry

            jax.lax.fori_loop(0, nreq, req, 0) if not self.select_owned else self._owned_slots(ctx, nreq, npr, group, score_merge)  # q38 L1-SELLOOP
            if recent:
                self._recent_finish(ctx, l)
            if self.shard_index:
                exchange(ctx)
        elif self.shard_index:
            for q in range(nreq):
                ck, gc = group(q, raw[q * T : (q + 1) * T])

                @pl.when(q // npr == self._run(ctx))
                def _(q=q, ck=ck, gc=gc):
                    score_merge(
                        q, scr["qi_q"][q].astype(BF16), ck, gc, q % npr == 0, q % npr == npr - 1 or q == nreq - 1
                    )

                if not recent:
                    self._recent_tile(ctx, l, q)
            if recent:
                self._recent_finish(ctx, l)
            exchange(ctx)
        else:
            for q in range(nreq):
                qr = scr["qi_q"][q].astype(BF16)
                self._score_request(ctx, q, qr, self.tab_base(ctx, l), last=q == nreq - 1, row0=0)
                ck, gc = group(q, raw[q * T : (q + 1) * T])
                s_new = ix.score_rows(qr, jnp.broadcast_to(ck.astype(BF16), (8, ix.IDX_DIM)))[:, :1]
                # The completed group's fresh key replaces its stale cached column.
                scr["qi_s"][0:T] = jnp.where(gid == gc, s_new.reshape(T, 1, 1, 1), scr["qi_s"][0:T])
                if not recent:
                    self._recent_tile(ctx, l, q)
                select_rows(q * T, T, 0)
            if recent:
                self._recent_finish(ctx, l)
        for c in outs:
            c.wait()
        if batch:
            for c in self._new_group_outs(ctx, l):
                c.wait()
        if self.debug:  # the kernel's queries (and, without B2, the pool-path ids)
            from .qsa_full_b import DBG_IDS, DBG_IQ

            for h in range(ix.IDX_HEADS):
                scr["qi_dbg"][:, h * ix.IDX_DIM : (h + 1) * ix.IDX_DIM] = iq[h]
            pairs = ((scr["qi_dbg"], DBG_IQ),) + (() if lean else ((scr["qi_id"], DBG_IDS),))
            for src, dst in pairs:
                c = pltpu.make_async_copy(src, ctx.O[dst].at[o, pl.ds(0, MB)], scr["qi_sem"].at[0])
                c.start()
                c.wait()

class _TwinSinkMixin:
    """The layer-47 sink export under `twin_split`: each twin exports its own T / 2 rows of the pair's request at local
    rows `[i T / 2, (i + 1) T / 2)`, so the host's rank-major all-gather lays the rows out in request order."""

    def sink_rows(self, ex: ExecSpec) -> int:
        if not self._twin_on(ex):
            return super().sink_rows(ex)
        return self._shard_rows(ex)[0] * ex.T // 2

    def _sink_export(self, ctx: Any, q: Any, npr: int) -> None:
        if not self._twin_on(ctx.ex):
            return super()._sink_export(ctx, q, npr)
        from .qsa_full_lean import _union_pass, _union_prologue

        ex, scr = ctx.ex, ctx.scr
        T, K, S = ex.T, self.budget, self.max_groups // 128
        h = T // 2
        W = min(K, ua.UNION_CHUNK)
        assert K % W == 0, (K, W)
        consts = ua.union_consts(S, K)
        lid = jax.lax.broadcasted_iota(I32, (S, 128), 0) * 128 + jax.lax.broadcasted_iota(I32, (S, 128), 1)
        i = q - self._run(ctx) * npr
        par = jax.lax.rem(ctx.me, 2)

        @pl.when(ctx._l47_last)
        def _():
            for j in range(h):
                t = par * h + j
                r = q * T + t
                nvr = scr["qi_nv"][r][:, :1]
                b = jnp.where(lid < nvr, pltpu.bitcast(scr["qi_s"][t].reshape(S, 128), I32), -1)
                th, tm = scr["qi_th"][r][:, :1], scr["qi_tm"][r][:, :1]
                ov = nvr > K
                sel = (ov & ((b > th) | ((b == th) & (lid <= tm)))) | (~ov & (b >= 0))
                pro = _union_prologue(sel.astype(I32), consts)
                for j0 in range(0, K, W):
                    ids, _ = _union_pass(pro, consts, j0)
                    scr["qs_row"][0, :, pl.ds(j0, W)] = ids
                c = pltpu.make_async_copy(scr["qs_row"], ctx.O[SINK_IDS].at[pl.ds(i * h + j, 1)], scr["qs_sem"].at[0])
                c.start()
                c.wait()


