TWIN_KEY = "twin_split"
TWIN_TRACES: list = []  # (class name, qx_early, l47_sink, select_owned) per block built (tests / engagement)
TWIN_SELECT_TRACES: dict = {}  # (MB, R, T) -> count of traced twin selections (tests / engagement)
