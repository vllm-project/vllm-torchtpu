def twin_step_block(indexed: dict, qsa: dict | None) -> Any:
    """None unless `twin_split` is in the indexed options; else the twin class for (X-DCP-QX-EARLY present, layer-47 sink)
    built with the options (`select_owned` taken out and engaged on the block, as qsa_full_idx.lean_step_block does).
    Refuses every configuration it is not built for."""
    if not indexed.get(TWIN_KEY):
        return None
    owned = int(indexed.get("select_owned", 0) or 0)
    sink = bool(indexed.get(SINK_KEY))
    rest = {k: v for k, v in indexed.items() if k not in (TWIN_KEY, "select_owned", SINK_KEY)}
    problems = []
    if int(rest.get("dcp", 1) or 1) != 4:
        problems.append("main-KV DCP 4")
    if not owned:
        problems.append("VLLM_TPU_MK_SELECT_OWNED (L1-SELLOOP)")
    for k, what in (("shard_index", "wholeshard"), ("loop_requests", "wholeloop"), ("union_attn", "wholeunion"),
                    ("union_lean", "VLLM_TPU_MK_UNION_LEAN"), ("union_bounded", "VLLM_TPU_MK_UNION_BOUNDED"),
                    ("slot_batch", "VLLM_TPU_MK_SLOT_BATCH")):
        if not rest.get(k):
            problems.append(what)
    if int(rest.get("union_qsplit", 0) or 0) != 1:
        problems.append("VLLM_TPU_MK_UNION_QSPLIT=1")
    if rest.get("compressed_dcp"):
        problems.append("no compressed-key DCP")
    if int(rest.get("union_pipe", 0) or 0):
        problems.append("no VLLM_TPU_MK_UNION_PIPE")
    if problems:
        raise ValueError("q38 HXIDX VLLM_TPU_MK_IDX_TWIN=1 needs: " + ", ".join(problems))
    qx = "qx_early" in rest
    cls = TWIN_CLASSES[(qx, sink)]
    kw = dict(rest, **(qsa or {}), twin_split=1)
    if sink:
        kw["l47_sink"] = True
    blk = cls(**kw)
    blk.engage_select_owned(owned)
    rec = (cls.__name__, qx, sink, owned)
    TWIN_TRACES.append(rec)
    if rec not in _LOGGED:
        _LOGGED.add(rec)
        _log.info("q38 HXIDX twin selection split: block %s qx_early=%s l47_sink=%s select_owned=%d (<= R / 2 request "
                  "slots; inert above)", *rec)
    return blk
