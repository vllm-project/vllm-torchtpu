"""q38 HXIDX (C-R): the whole step's in-kernel selection split over a twin core pair at <= R / 2 request slots.

Option `twin_split` (VLLM_TPU_MK_IDX_TWIN=1, default off) on the L1-IDX DCP-4 group block. At the 16-row bucket the whole
step has 4 request slots and 8 cores, so with the sharded indexer (one owner per slot) half the cores own nothing and wait
in the exchange. With `twin_split` a slot is owned by a twin pair (cores 2p, 2p + 1 = `me ^ 1`, the all-reduce's twin):

  1. both twins score the whole request (`_score_request`, unchanged: the compressed keys are replicated per rank);
  2. each twin runs the thresholds and the row loop for HALF of the request's T verify rows (even core rows 0 .. T/2 - 1,
     odd core the rest). Every row has its own threshold (`thresholds_radix2` reduces per row only), so no merge exists;
  3. ONE twin exchange (`me ^ 1`, on-chip) swaps the code bits the partner's union halves need (rows s with s % 2 equal to
     the partner's parity, `[S / 2, 128]` int32) and the partner rows' `qi_kvl`, `qc_sga`, `qi_th`, `qi_tm`, `qi_nv`;
  4. each twin compacts the DCP union halves of its parity (even core halves 0, 2; odd core 1, 3) from its code rows OR
     the partner's (QSPLIT 1 rows, `_compact_rows` unchanged), so every core compacts its own half locally;
  5. the all-rank exchange sends each half only to the same-parity cores (`me ^ 2`, `me ^ 4`, `me ^ 6`), into the slot
     of the request's pair, which is the slot every reader already uses (`q // npr`).

Bitwise by construction: identical inputs, row-independent selection, integer OR of the code bits, the unchanged
compaction on identical rows; every consumed value is the owner's exactly. (A receiver's `qu_n` lanes for halves of the
other parity are not refreshed; only `qu_n[q, me % D]` is read, `qsa_full_lean.py` union attention / issue prep.)
At more slots than R / 2 the option is inert (every method falls back to the base code).

`twin_step_block` builds the block (with L1-SELLOOP's `select_owned` engaged, and the layer-47 sink export `l47_sink`
when present: each twin exports its own rows, `T / 2` per rank in rank order, which the host's rank-major all-gather
(`qwen38_l47fold.gather_runs`) lays out in request order). `_select` below is GENERATED by
scratch/hxdev/c/gen_qsa_full_twin.py from `qsa_full_idx._IdxMixin._select` with pinned substitutions.
"""

